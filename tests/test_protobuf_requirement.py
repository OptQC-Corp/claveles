"""The declared protobuf requirement has to cover what the generated code demands.

Every module under ``src/claveles/pb`` opens with ``ValidateProtobufRuntimeVersion``, which raises on a
runtime older than the protoc that generated it. That version is regenerated by CI whenever the protos
change, so it moves on its own; the requirement in ``pyproject.toml`` does not. When the two drift
apart the requirement permits a runtime that cannot import the package at all, and only an install that
resolves to the low end of the range -- a lockfile, most likely -- notices. `pip install`, which CI
uses, takes the newest match and sails past it.
"""

from __future__ import annotations

import re
from importlib import metadata
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.version import Version

PB_ROOT = Path(__file__).resolve().parent.parent / "src" / "claveles" / "pb"

GENCODE_CALL = re.compile(
    r"ValidateProtobufRuntimeVersion\(\s*_runtime_version\.Domain\.\w+,\s*(\d+),\s*(\d+),\s*(\d+),",
)


def gencode_versions() -> dict[Path, Version]:
    """Read the runtime version each generated module requires.

    Returns:
        dict[Path, Version]: The version demanded by every generated module that states one.
    """
    found = {}
    for path in sorted(PB_ROOT.rglob("*_pb2.py")):
        match = GENCODE_CALL.search(path.read_text())
        if match is not None:
            found[path] = Version(".".join(match.groups()))
    return found


def declared_protobuf_requirement() -> Requirement:
    """Return the protobuf requirement this package declares.

    Read from the installed metadata rather than from ``pyproject.toml``, so what is checked is the
    requirement an installer actually resolves against.

    Returns:
        Requirement: The declared requirement.
    """
    declared = [Requirement(raw) for raw in metadata.requires("claveles-core") or [] if raw.startswith("protobuf")]
    assert len(declared) == 1, f"expected one protobuf requirement, found {declared}"
    return declared[0]


def test_the_generated_modules_agree_on_a_runtime_version() -> None:
    """One codegen run produces one version, so a second one means a partial regeneration."""
    versions = gencode_versions()

    assert versions, f"no generated modules with a runtime version found under {PB_ROOT}"
    assert len(set(versions.values())) == 1, {str(p): str(v) for p, v in versions.items()}


def test_protobuf_lower_bound_covers_gencode() -> None:
    """No runtime the requirement permits may be too old for the generated code.

    Checked by asking the requirement about the gencode version itself and about the release below it,
    which is the one an installer resolving to the low end of a stale range would pick.
    """
    required = next(iter(gencode_versions().values()))
    specifier = declared_protobuf_requirement().specifier

    assert specifier.contains(str(required)), (
        f"the generated code needs protobuf {required}, which the declared requirement excludes"
    )
    if required.micro > 0:
        too_old = Version(f"{required.major}.{required.minor}.{required.micro - 1}")
    else:
        too_old = Version(f"{required.major}.{required.minor - 1}.0")
    assert not specifier.contains(str(too_old)), (
        f"the declared requirement permits protobuf {too_old}, which cannot import the generated code "
        f"(it needs {required}). Raise the lower bound in pyproject.toml."
    )


def test_the_installed_runtime_is_one_the_generated_code_accepts() -> None:
    """Belt and braces: the environment running this suite satisfies its own declaration."""
    installed = Version(metadata.version("protobuf"))
    required = next(iter(gencode_versions().values()))

    if installed < required:
        pytest.fail(f"protobuf {installed} is installed, but the generated code needs {required}")
    assert declared_protobuf_requirement().specifier.contains(str(installed))
